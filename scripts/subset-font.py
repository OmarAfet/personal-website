"""Subsets the IBM VGA 8x16 web font to the characters the site can show,
writes it as WOFF2, and writes src/app/fonts/vga.css with its fallbacks.

Usage (needs fontTools and brotli: pip install fonttools brotli):
    python3 -I scripts/subset-font.py

Kept: printable ASCII and Latin-1 (anything a visitor can type in the shell),
general punctuation, arrows, box drawing, block elements and geometric shapes.
Dropped: the Latin Extended, Greek and Cyrillic glyphs of the "Plus" font.
22.6 KB WOFF -> about 5 KB WOFF2 (2026-10-19, for Lighthouse mobile LCP).
The full WOFF stays for the Open Graph image (satori cannot read WOFF2).
The subset is an adaptation of a CC BY-SA 4.0 font, so it stays CC BY-SA 4.0.

vga.css defines the fallbacks: local monospace fonts scaled to the same
0.5 em advance as VGA 8x16. When the font arrives after the first layout,
every column stays where it was; with an unscaled fallback the text moved
(Lighthouse CLS 0.088, cause "Web font loaded", 2026-10-19). Embedding the font
as a data: URL was tried and dropped: Next.js inlines the CSS into the HTML
and twice more into the RSC payload, so the font would ship three times.
"""

from pathlib import Path

from fontTools import subset

FONTS = Path(__file__).resolve().parent.parent / "src/app/fonts"
SOURCE = FONTS / "WebPlus_IBM_VGA_8x16.woff"
TARGET = FONTS / "WebPlus_IBM_VGA_8x16-subset.woff2"
CSS = FONTS / "vga.css"

RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x00FF),  # Latin-1
    (0x2010, 0x2027),  # dashes, quotes, bullet, ellipsis
    (0x2190, 0x21FF),  # arrows
    (0x2500, 0x259F),  # box drawing, block elements
    (0x25A0, 0x25FF),  # geometric shapes
    (0x2713, 0x2713),  # check mark
]

# Local monospace fonts and their advance width (units per em), scaled so one
# character is 0.5 em wide, like VGA 8x16. local() matches a font's full or
# PostScript name, not its family name ("Menlo" alone matches nothing on macOS).
FALLBACKS = [
    ("VGA Fallback Consolas", ["Consolas"], 1126 / 2048),
    (
        "VGA Fallback Menlo",
        ["Menlo Regular", "Menlo-Regular", "DejaVu Sans Mono", "DejaVuSansMono"],
        1233 / 2048,
    ),
    (
        "VGA Fallback Courier",
        [
            "Courier New",
            "CourierNewPSMT",
            "Liberation Mono",
            "LiberationMono",
            "Roboto Mono",
            "RobotoMono-Regular",
            "Droid Sans Mono",
            "DroidSansMono",
        ],
        1229 / 2048,
    ),
]

# VGA 8x16 vertical metrics: ascent 1200 and descent 400 of 1600 units, no
# line gap. The overrides are scaled by size-adjust, so they are divided by it.
ASCENT, DESCENT = 0.75, 0.25


def write_css() -> None:
    faces = [
        "/* Generated by scripts/subset-font.py; edit that script, not this file.",
        "   Fallbacks for the console font, listed in layout.tsx (next/font). */",
    ]
    for name, sources, advance in FALLBACKS:
        scale = 0.5 / advance
        faces += [
            "@font-face {",
            f'  font-family: "{name}";',
            f"  src: {', '.join(f'local({chr(34)}{s}{chr(34)})' for s in sources)};",
            f"  size-adjust: {scale * 100:.2f}%;",
            f"  ascent-override: {ASCENT / scale * 100:.2f}%;",
            f"  descent-override: {DESCENT / scale * 100:.2f}%;",
            "  line-gap-override: 0%;",
            "}",
        ]
    CSS.write_text("\n".join(faces) + "\n")


def main() -> None:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    options.name_IDs = ["*"]  # keep the copyright and license names
    font = subset.load_font(str(SOURCE), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[u for a, b in RANGES for u in range(a, b + 1)])
    subsetter.subset(font)
    subset.save_font(font, str(TARGET), options)
    write_css()
    print(f"{SOURCE.name} {SOURCE.stat().st_size} B -> {TARGET.name} {TARGET.stat().st_size} B")
    print(f"wrote {CSS} ({CSS.stat().st_size} B)")


if __name__ == "__main__":
    main()
